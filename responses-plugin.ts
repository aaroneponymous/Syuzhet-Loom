// Local-only logging of responses typed into the viewer.
// While `npm run dev` or `npm run preview` is running, the viewer reads and writes
// responses/responses.json through /__responses, and a readable responses/RESPONSES.md is
// regenerated on every change. Nothing leaves this machine.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { Connect, Plugin } from 'vite';

const DIR = resolve('responses');
const FILE = resolve(DIR, 'responses.json');
const MD = resolve(DIR, 'RESPONSES.md');

interface Entry {
  id: string;
  targetKey: string;
  targetType: string;
  targetLabel: string;
  context: string;
  link: string;
  kind: string;
  choice?: string;
  text: string;
  author?: string;
  createdAt: string;
  updatedAt: string;
  reviewed?: boolean;
  reply?: string;
}
interface Doc {
  version: 1;
  note: string;
  responses: Entry[];
}
const NOTE =
  'Responses logged in the Syuzhet Loom viewer. They are input for review, not recorded product decisions. "reviewed" and "reply" are filled in by the reviewer.';

function read(): Doc {
  if (!existsSync(FILE)) return { version: 1, note: NOTE, responses: [] };
  try {
    const d = JSON.parse(readFileSync(FILE, 'utf8'));
    return { version: 1, note: NOTE, responses: Array.isArray(d.responses) ? d.responses : [] };
  } catch {
    // never overwrite a file we could not read
    throw new Error('responses/responses.json is not valid JSON; fix or remove it');
  }
}

const KIND: Record<string, string> = { answer: 'Answer', decision: 'Decision', correction: 'Correction', question: 'Question', note: 'Note' };
function toMarkdown(d: Doc): string {
  const block = (e: Entry) =>
    [
      `### ${e.targetLabel}`,
      '',
      `- **Target:** ${e.context} · \`${e.targetKey}\` · link \`${e.link}\``,
      `- **Kind:** ${KIND[e.kind] ?? e.kind}${e.author ? ` · **By:** ${e.author}` : ''} · **Updated:** ${e.updatedAt}`,
      e.choice ? `- **Chosen option:** ${e.choice}` : '',
      '',
      e.text ? e.text.split('\n').map((l) => `> ${l}`).join('\n') : '> (no text)',
      e.reply ? `\n**Reviewer reply:** ${e.reply}` : '',
      '',
    ]
      .filter((l) => l !== '')
      .join('\n') + '\n';
  const fresh = d.responses.filter((e) => !e.reviewed);
  const done = d.responses.filter((e) => e.reviewed);
  return [
    '# Responses logged in the viewer',
    '',
    '**These are responses awaiting review, not recorded product decisions.** A response becomes a decision only when it is recorded in the product workspace.',
    '',
    'Generated from `responses.json` on every change. Do not edit this file; edit responses in the viewer.',
    '',
    `## Awaiting review (${fresh.length})`,
    '',
    ...(fresh.length ? fresh.map(block) : ['None.', '']),
    `## Reviewed (${done.length})`,
    '',
    ...(done.length ? done.map(block) : ['None.', '']),
  ].join('\n');
}
function write(d: Doc) {
  mkdirSync(DIR, { recursive: true });
  writeFileSync(FILE, JSON.stringify(d, null, 2) + '\n');
  writeFileSync(MD, toMarkdown(d));
}

const str = (v: unknown, max: number) => (typeof v === 'string' ? v.slice(0, max) : '');

const handler: Connect.NextHandleFunction = (req, res, next) => {
  if (!req.url || !req.url.split('?')[0].endsWith('/__responses')) return next();
  const send = (code: number, body: unknown) => {
    res.statusCode = code;
    res.setHeader('Content-Type', 'application/json');
    res.setHeader('Cache-Control', 'no-store');
    res.end(JSON.stringify(body));
  };
  try {
    if (req.method === 'GET') return send(200, read());
    if (req.method === 'DELETE') {
      const id = new URL(req.url, 'http://localhost').searchParams.get('id');
      const d = read();
      d.responses = d.responses.filter((e) => e.id !== id);
      write(d);
      return send(200, d);
    }
    if (req.method === 'POST') {
      let raw = '';
      req.on('data', (c) => {
        raw += c;
        if (raw.length > 200_000) req.destroy();
      });
      req.on('end', () => {
        try {
          const b = JSON.parse(raw);
          if (!str(b.id, 80) || !str(b.targetKey, 300)) return send(400, { error: 'id and targetKey are required' });
          const d = read();
          const prev = d.responses.find((e) => e.id === b.id);
          const now = new Date().toISOString();
          const entry: Entry = {
            id: str(b.id, 80),
            targetKey: str(b.targetKey, 300),
            targetType: str(b.targetType, 30),
            targetLabel: str(b.targetLabel, 300),
            context: str(b.context, 300),
            link: str(b.link, 400),
            kind: str(b.kind, 30) || 'note',
            choice: str(b.choice, 1000) || undefined,
            text: str(b.text, 20000),
            author: str(b.author, 80) || undefined,
            createdAt: prev?.createdAt ?? now,
            updatedAt: now,
            // an edited response needs reviewing again; the reviewer's earlier reply is kept for context
            reviewed: false,
            reply: prev?.reply,
          };
          d.responses = prev ? d.responses.map((e) => (e.id === entry.id ? entry : e)) : [...d.responses, entry];
          write(d);
          send(200, d);
        } catch (e) {
          send(400, { error: String(e) });
        }
      });
      return;
    }
    send(405, { error: 'method not allowed' });
  } catch (e) {
    send(500, { error: String(e) });
  }
};

export function responsesPlugin(): Plugin {
  return {
    name: 'syuzhet-loom-responses',
    configureServer(server) {
      server.middlewares.use(handler);
    },
    configurePreviewServer(server) {
      server.middlewares.use(handler);
    },
  };
}
