// Maps every acceptance criterion to model elements, an explicitly non-visual rule, or a gap.
// Writes COVERAGE.md. A mapping shows where a criterion is represented; it does not show the model is right.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { machineList, modelMeta, nonVisualRules, openQuestions } from '../src/model/index';
import { REPO_DIR } from './workspace';

const { refs, record } = JSON.parse(readFileSync(join(REPO_DIR, 'src/model/generated/sources.json'), 'utf8'));
const acIds = Object.keys(refs)
  .filter((k) => k.startsWith('AC-'))
  .sort((a, b) => a.slice(0, 6).localeCompare(b.slice(0, 6)) || +a.slice(7) - +b.slice(7));
// one section per journey that has criteria, in id order
const journeyIds = [...new Set(acIds.map((id) => id.slice(3, 6)))].sort();

const cites = new Map<string, string[]>();
const add = (id: string, where: string) => cites.set(id, [...(cites.get(id) ?? []), where]);
let nStates = 0;
let nTrans = 0;
let nOpen = 0;
let nInterp = 0;
for (const m of machineList) {
  for (const r of m.refs ?? []) add(r, `${m.id}`);
  nInterp += m.interpretations?.length ?? 0;
  for (const s of m.states) {
    nStates++;
    if (s.open) nOpen++;
    if (s.interpretation) nInterp++;
    for (const r of s.refs ?? []) add(r, `${m.id}/${s.id}`);
  }
  for (const t of m.transitions) {
    nTrans++;
    if (t.open) nOpen++;
    if (t.interpretation) nInterp++;
    for (const r of t.refs ?? []) add(r, `${m.id}/${t.id}`);
  }
}
const nonVisual = new Map(nonVisualRules.map((r) => [r.id, r.reason]));
const trim = (s: string, n = 110) => (s.length > n ? s.slice(0, n - 1) + '…' : s);
const cell = (s: string) => s.replace(/\|/g, '\\|');

const rows: Record<string, string[]> = Object.fromEntries(journeyIds.map((j) => [j, [] as string[]]));
const tally = { modelled: 0, nonVisual: 0, merged: 0, withdrawn: 0, gap: 0 };
const gaps: string[] = [];
for (const id of acIds) {
  const j = id.slice(3, 6);
  const e = refs[id];
  const where = cites.get(id) ?? [];
  let status: string;
  let detail: string;
  if (/^Withdrawn for now/.test(e.text ?? '')) {
    status = 'Withdrawn for now';
    detail = `${e.text}.${where.length ? ' **Still cited by: ' + where.join(', ') + '**' : ''}`;
    tally.withdrawn++;
  } else if (/Merged into/.test(e.note ?? '')) {
    status = 'Merged';
    detail = e.note;
    tally.merged++;
  } else if (nonVisual.has(id)) {
    status = 'Non-visual rule';
    detail = `${nonVisual.get(id)}${where.length ? ` Recorded on: ${where.map((w) => `\`${w}\``).join(', ')}` : ''}`;
    tally.nonVisual++;
  } else if (where.length) {
    status = 'Modelled';
    detail = where.map((w) => `\`${w}\``).join(', ');
    tally.modelled++;
  } else {
    status = '**GAP**';
    detail = 'Not represented in the model.';
    tally.gap++;
    gaps.push(id);
  }
  rows[j].push(`| ${id} | ${cell(trim(e.text))} | ${status} | ${cell(detail)} |`);
}

const decisions = Object.keys(refs).filter((k) => /^D-\d+$/.test(k)).sort((a, b) => +a.slice(2) - +b.slice(2));
const uncitedDecisions = decisions.filter((d) => !cites.has(d));
const openRows = openQuestions
  .filter((q) => ['unresolved', 'discrepancy', 'ambiguity'].includes(q.status))
  .map((q) => {
    const marked: string[] = [];
    for (const m of machineList) {
      for (const s of m.states) if (s.open?.questions.includes(q.id)) marked.push(`\`${m.id}/${s.id}\``);
      for (const t of m.transitions) if (t.open?.questions.includes(q.id)) marked.push(`\`${m.id}/${t.id}\``);
    }
    return `| ${q.id} | ${cell(q.title)} | ${marked.length ? marked.join(', ') : '**not marked on any element**'} |`;
  });

const md = `# Coverage report

Generated by \`npm run coverage\` from the model and the bundled source wording. It shows **where** each acceptance criterion is represented. It does not show that the representation is correct: that needs a human review of the model against the requirement.

Model: ${modelMeta.title}. Sources: \`${record.archive.folder}\`, extracted ${record.extractedAt.slice(0, 10)}; journeys ${journeyIds.join(', ') || 'none'}; ${decisions.length} decisions. See SOURCE_VERSIONS.md.

## Summary

| Measure | Count |
|---|---|
| Machines | ${machineList.length} (of which ${machineList.filter((m) => m.kind === 'boundary').length} are boundaries without internals) |
| States and regions | ${nStates} |
| Transitions and signals | ${nTrans} |
| Elements marked OPEN | ${nOpen} |
| Modelling interpretations marked | ${nInterp} |
| Acceptance criteria | ${acIds.length} |
| — modelled as states or transitions | ${tally.modelled} |
| — recorded as non-visual rules | ${tally.nonVisual} |
| — merged ids (note says "Merged into …"; ids kept) | ${tally.merged} |
| — withdrawn for now (text starts "Withdrawn for now"; ids kept) | ${tally.withdrawn} |
| — **gaps** | ${tally.gap}${gaps.length ? ` (${gaps.join(', ')})` : ''} |
| Decisions cited by at least one element | ${decisions.length - uncitedDecisions.length} of ${decisions.length} |

"Modelled" means the criterion's id is cited by at least one state or transition whose description, rules, guard or effects carry the behaviour. "Non-visual rule" means the criterion constrains wording, presentation or something that never happens, so it is recorded as a rule on the nearest element instead of being drawn as its own state or transition.

## Open points and where they are marked

| Id | Point | Elements carrying the OPEN mark |
|---|---|---|
${openRows.join('\n')}

## Decisions not cited by any element

${uncitedDecisions.length ? uncitedDecisions.map((d) => `- ${d}: ${trim(refs[d].text, 150)}`).join('\n') : 'None.'}

A decision may be uncited because it is about the programme of work, a wording rule, or a journey that is not modelled. They are listed so the omission is visible, not hidden.

${journeyIds.map((j) => `## ${j} acceptance criteria\n\n| Id | Criterion | Status | Where |\n|---|---|---|---|\n${rows[j].join('\n')}\n`).join('\n')}`;
writeFileSync(join(REPO_DIR, 'COVERAGE.md'), md);
console.log(tally, 'gaps:', gaps.join(' ') || 'none');
console.log('uncited decisions:', uncitedDecisions.join(' '));
